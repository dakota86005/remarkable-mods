#!/usr/bin/env python3
"""Build Dakota's private Vellum (apk v2) repository.

Usage: python3 build_repo.py [--key ../vellum-repo-signing/dakota-mods.rsa] [--out docs]

Reads packages/<name>/pkg.json, packages/<name>/files/ (laid out like the
tablet's filesystem) and optional lifecycle scripts (post-install,
post-upgrade, pre-deinstall, post-deinstall). Writes signed .apk files and a
signed APKINDEX.tar.gz to <out>/aarch64/ (docs/ is served by GitHub Pages), the layout apk and Vellum expect.

Only needs Python 3 and the `cryptography` package.
"""
import argparse, base64, gzip, hashlib, io, json, os, sys, tarfile, time

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding

ARCH = "aarch64"          # reMarkable Paper Pro family
SCRIPTS = ["pre-install", "post-install", "pre-upgrade", "post-upgrade",
           "pre-deinstall", "post-deinstall"]
MAINTAINER = "Dakota"

# Debounced UI restart: several packages in one transaction restart once.
RESTART = r'''# Restart the reMarkable UI with mods once apk has finished.
_tok="$$-$(date +%s)"
echo "$_tok" > /tmp/.dakota-mods-restart
( sleep 5
  [ "$(cat /tmp/.dakota-mods-restart 2>/dev/null)" = "$_tok" ] || exit 0
  rm -f /tmp/.dakota-mods-restart
  [ -x /home/root/xovi/start ] && /home/root/xovi/start
) </dev/null >/dev/null 2>&1 &'''


def epoch():
    return int(os.environ.get("SOURCE_DATE_EPOCH", time.time()))


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def tar_bytes(members, fmt=tarfile.PAX_FORMAT, cut=False):
    """members: list of (TarInfo, bytes|None). cut drops the end-of-archive blocks."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=fmt) as t:
        for ti, data in members:
            t.addfile(ti, io.BytesIO(data) if data is not None else None)
    raw = buf.getvalue()
    if cut:
        # Python pads to a 10240-byte record: strip all trailing zero blocks.
        end = len(raw)
        while end >= 512 and raw[end - 512:end] == b"\0" * 512:
            end -= 512
        raw = raw[:end]
    return raw


def info(name, size=0, mode=0o644, kind=tarfile.REGTYPE, mtime=None):
    ti = tarfile.TarInfo(name)
    ti.size, ti.mode, ti.type = size, mode, kind
    ti.uid = ti.gid = 0
    ti.uname = ti.gname = "root"
    ti.mtime = epoch() if mtime is None else mtime
    return ti


def sign(key, data: bytes) -> bytes:
    return key.sign(data, padding.PKCS1v15(), hashes.SHA1())


def sig_stream(key, keyname, data: bytes) -> bytes:
    s = sign(key, data)
    ti = info(f".SIGN.RSA.{keyname}", len(s))
    return gz(tar_bytes([(ti, s)], fmt=tarfile.USTAR_FORMAT, cut=True))


def build_package(pkgdir, key, keyname, outdir):
    meta = json.load(open(os.path.join(pkgdir, "pkg.json")))
    name, ver = meta["pkgname"], f'{meta["pkgver"]}-r{meta.get("pkgrel", 0)}'
    root = os.path.join(pkgdir, "files")

    # ---- data section
    members, isize = [], 0
    for dirpath, dirs, files in os.walk(root):
        dirs.sort()
        rel = os.path.relpath(dirpath, root)
        if rel != ".":
            members.append((info(rel, mode=0o755, kind=tarfile.DIRTYPE), None))
        for fn in sorted(files):
            full = os.path.join(dirpath, fn)
            data = open(full, "rb").read()
            arc = fn if rel == "." else f"{rel}/{fn}"
            mode = 0o755 if (fn.endswith(".sh") or os.access(full, os.X_OK)) else 0o644
            ti = info(arc, len(data), mode)
            ti.pax_headers = {"APK-TOOLS.checksum.SHA1": hashlib.sha1(data).hexdigest()}
            members.append((ti, data))
            isize += len(data)
    data_gz = gz(tar_bytes(members))
    datahash = hashlib.sha256(data_gz).hexdigest()

    # ---- control section
    deps = meta.get("depends", [])
    pkginfo = [
        "# Generated by build_repo.py",
        f"pkgname = {name}", f"pkgver = {ver}", f'pkgdesc = {meta["pkgdesc"]}',
        f'url = {meta.get("url", "")}', f"builddate = {epoch()}",
        f"packager = {MAINTAINER}", f"size = {isize}", "arch = noarch",
        f"origin = {name}", f"maintainer = {MAINTAINER}",
        f'license = {meta.get("license", "custom")}',
    ] + [f"depend = {d}" for d in deps] + [f"datahash = {datahash}"]
    pkginfo_b = ("\n".join(pkginfo) + "\n").encode()
    ctrl = [(info(".PKGINFO", len(pkginfo_b)), pkginfo_b)]
    for s in SCRIPTS:
        p = os.path.join(pkgdir, s)
        if os.path.exists(p):
            body = open(p).read().replace("@RESTART@", RESTART).encode()
            ctrl.append((info("." + s, len(body), 0o755), body))
    ctrl_gz = gz(tar_bytes(ctrl, fmt=tarfile.USTAR_FORMAT, cut=True))

    apk = sig_stream(key, keyname, ctrl_gz) + ctrl_gz + data_gz
    fname = f"{name}-{ver}.apk"
    open(os.path.join(outdir, fname), "wb").write(apk)

    entry = [
        "C:Q1" + base64.b64encode(hashlib.sha1(ctrl_gz).digest()).decode(),
        f"P:{name}", f"V:{ver}", f"A:{ARCH}", f"S:{len(apk)}", f"I:{isize}",
        f'T:{meta["pkgdesc"]}', f'U:{meta.get("url", "")}',
        f'L:{meta.get("license", "custom")}', f"o:{name}",
        f"m:{MAINTAINER}", f"t:{epoch()}",
    ]
    if deps:
        entry.append("D:" + " ".join(deps))
    print(f"  {fname}  ({len(apk)//1024} KB, {len(members)} entries)")
    return "\n".join(entry) + "\n"


def main():
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.abspath(__file__))
    # The private key never lives in this (public) repo.
    ap.add_argument("--key", default=os.path.join(here, "..", "vellum-repo-signing", "dakota-mods.rsa"))
    ap.add_argument("--out", default=os.path.join(here, "docs"))
    ap.add_argument("--packages", default=os.path.join(here, "packages"))
    a = ap.parse_args()

    keypem = os.environ.get("SIGNING_KEY")
    keypem = keypem.encode() if keypem else open(a.key, "rb").read()
    key = serialization.load_pem_private_key(keypem, password=None)
    keyname = "dakota-mods.rsa.pub"

    outdir = os.path.join(a.out, ARCH)
    os.makedirs(outdir, exist_ok=True)
    for f in os.listdir(outdir):
        if f.endswith(".apk") or f == "APKINDEX.tar.gz":
            os.remove(os.path.join(outdir, f))

    entries = []
    for name in sorted(os.listdir(a.packages)):
        d = os.path.join(a.packages, name)
        if os.path.isfile(os.path.join(d, "pkg.json")):
            entries.append(build_package(d, key, keyname, outdir))

    index = "\n".join(entries).encode()
    desc = b"Dakota's reMarkable mods"
    unsigned = gz(tar_bytes([(info("DESCRIPTION", len(desc)), desc),
                             (info("APKINDEX", len(index)), index)],
                            fmt=tarfile.USTAR_FORMAT))
    open(os.path.join(outdir, "APKINDEX.tar.gz"), "wb").write(
        sig_stream(key, keyname, unsigned) + unsigned)
    print(f"Wrote {len(entries)} packages + APKINDEX.tar.gz to {outdir}")


if __name__ == "__main__":
    sys.exit(main())
